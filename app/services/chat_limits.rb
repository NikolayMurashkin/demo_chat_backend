# frozen_string_literal: true

# Пороги частоты для всех дорогих действий чата в одном месте.
#
# Почему централизованно: раньше числа лежали прямо в каналах и контроллерах, и подобрать их
# по живому стенду было нельзя — каждая правка требовала релиза. Теперь любой порог
# переопределяется переменной окружения `CHAT_LIMIT_<ИМЯ>` (для счётчиков — `CHAT_MAX_<ИМЯ>`),
# то есть лечится перезапуском, а не выкаткой.
#
# Как выбраны значения. Мессенджеры, которые работают, душат только запись — отправку,
# загрузку, приглашения, — и почти никогда не трогают чтение, подключение и подписку:
# те повторяются при каждом реконнекте, а реконнект человек не контролирует. Ещё они
# никогда не молчат в ответ: Telegram отвечает FLOOD_WAIT с числом секунд, Discord —
# 429 с `retry_after`. Здесь та же логика: пороги подняты до значений, которых обычный
# человек не достигает даже впятером с одного Wi-Fi, а всё, что упёрлось, попадает в лог
# и возвращается клиенту явно.
#
# Ключи по IP оставлены только как грубый потолок против одиночного флуда и намеренно
# на порядок выше пользовательских: за одним адресом сидит целый офис (или VPN-выход),
# и тесный общий бюджет запирает чат всем сразу — ровно тот случай, ради которого
# лимиты и переразмечались.
class ChatLimits
  # [лимит, период в секундах]
  RATES = {
    # --- Соединение и кадры. Реконнект инициирует сеть, а не человек: душить его нельзя. ---
    ws_connect_ip: [3_000, 60],
    ws_connect_user: [120, 60],
    ws_frame: [900, 60],

    # --- Действия в комнате ---
    message: [120, 60],
    read: [600, 60],
    typing: [60, 10],
    reaction: [90, 60],
    pin: [60, 60],
    edit: [60, 60],
    delete: [60, 60],

    # --- HTTP ---
    http_user: [1_200, 60],
    http_ip: [6_000, 60],
    upload_user: [60, 60],
    upload_ip: [600, 60],
    forward: [30, 60],
    invite_join: [30, 60],
    poll_create: [30, 60],
    poll_vote: [120, 60],

    # --- Сигналинг звонка ---
    # ICE считаем на звонок, а не на минуту: кандидатов столько, сколько у машины сетевых
    # интерфейсов, и на ноутбуке с VPN их десятки. Минутный бюджет выедала вторая попытка
    # дозвона, причём отбрасывались последние кандидаты — то есть srflx, единственные,
    # которыми соединяются разные сети. Звонок длиной в пять минут в этот бюджет укладывается
    # с запасом, а перебор чужих call_id ограничен отдельно.
    call_ice: [600, 300],
    call_setup: [30, 60],
    call_control: [60, 60]
  }.freeze

  # Счётчики, а не частоты: сколько одновременных сокетов держим на человека.
  # Пять компьютеров по три вкладки — это пятнадцать, и упираться в потолок человек не должен.
  COUNTS = {
    sockets_per_user: 30
  }.freeze

  class << self
    # Аргументы для ChatRateLimiter#allow?: `ChatRateLimiter.allow?(key, **ChatLimits.rate(:message))`.
    def rate(name)
      limit, period = RATES.fetch(name)

      {limit: env_integer("CHAT_LIMIT_#{name.upcase}", limit), period: period}
    end

    def count(name)
      env_integer("CHAT_MAX_#{name.upcase}", COUNTS.fetch(name))
    end

    private

    # Мусор в переменной не должен ронять приложение на старте и не должен молча снимать
    # ограничение: остаёмся на значении по умолчанию и говорим об этом в лог.
    def env_integer(name, fallback)
      raw = ENV[name]
      return fallback if raw.blank?

      value = Integer(raw, exception: false)
      return value if value&.positive?

      Rails.logger.warn("ChatLimits: значение #{name}=#{raw.inspect} не число, беру #{fallback}")
      fallback
    end
  end
end
